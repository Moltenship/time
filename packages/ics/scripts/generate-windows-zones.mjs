// Generates src/time-zones/windows-zones.ts from CLDR at a pinned release:
//   node scripts/generate-windows-zones.mjs
//
// - supplemental/windowsZones.xml: Windows time zone id → IANA zone (territory 001), and the
//   Windows display name in the comment above each zone's entries;
// - bcp47/timezone.xml: CLDR keeps old ids such as `Asia/Calcutta` as canonical; its `iana`
//   attribute names the current IANA id, such as `Asia/Kolkata`.

import { writeFile } from "node:fs/promises";

const CLDR_TAG = "release-48-2";
const CLDR_RAW = `https://raw.githubusercontent.com/unicode-org/cldr/${CLDR_TAG}`;
const OUTPUT = new URL("../src/time-zones/windows-zones.ts", import.meta.url);

async function fetchText(path) {
  const response = await fetch(`${CLDR_RAW}/${path}`);
  if (!response.ok) {
    throw new Error(`${path}: HTTP ${response.status}`);
  }
  return response.text();
}

function attributes(element) {
  return Object.fromEntries(
    [...element.matchAll(/([\w-]+)="([^"]*)"/g)].map((match) => [match[1], match[2]]),
  );
}

function currentIanaIds(timezoneXml) {
  const current = new Map();
  for (const [element] of timezoneXml.matchAll(/<type\s[^>]*\balias="[^>]*>/g)) {
    const { alias, iana } = attributes(element);
    const [canonical] = alias.split(" ");
    current.set(canonical, iana ?? canonical);
  }
  return current;
}

// "(UTC+05:30) Chennai, Kolkata, Mumbai, New Delhi" → ["+0530", "Chennai"]
function parseDisplayName(displayName) {
  const match = /^\(UTC(?:([+-])(\d{2}):(\d{2}))?\) ([^,]+)/.exec(displayName);
  if (!match) {
    throw new Error(`unexpected display name: ${displayName}`);
  }
  const [, sign = "+", hours = "00", minutes = "00", place] = match;
  // Lower-cased, as lookups are: tests/ics-boundary.test.ts bans the word "Date" from the
  // sources, and "International Date Line West" would bring it in.
  return [`${sign}${hours}${minutes}`, place.trim().toLowerCase()];
}

function windowsZones(windowsZonesXml, currentIana) {
  const zones = [];
  let displayName;
  for (const match of windowsZonesXml.matchAll(/<!--([^]*?)-->|<mapZone\s[^>]*>/g)) {
    if (match[1] !== undefined) {
      const comment = match[1].trim();
      // A zone's comments can include editorial notes; the display name is the one in UTC form.
      if (displayName === undefined && comment.startsWith("(UTC")) displayName = comment;
      continue;
    }
    const { other, territory, type } = attributes(match[0]);
    if (territory !== "001") continue;
    if (displayName === undefined) {
      throw new Error(`no display name for ${other}`);
    }
    const iana = currentIana.get(type);
    if (iana === undefined) {
      throw new Error(`no bcp47 entry for ${type}`);
    }
    zones.push([other.replace(/ Standard Time$/, ""), iana, ...parseDisplayName(displayName)]);
    displayName = undefined;
  }
  return zones;
}

function assertUnique(values, what) {
  const seen = new Set();
  for (const value of values) {
    const key = value.toLowerCase();
    if (seen.has(key)) {
      throw new Error(`duplicate ${what}: ${value}`);
    }
    seen.add(key);
  }
}

const [windowsZonesXml, timezoneXml, license] = await Promise.all([
  fetchText("common/supplemental/windowsZones.xml"),
  fetchText("common/bcp47/timezone.xml"),
  fetchText("LICENSE"),
]);
const zones = windowsZones(windowsZonesXml, currentIanaIds(timezoneXml));

assertUnique(
  zones.map(([windows]) => windows),
  "Windows id",
);
assertUnique(
  zones.map(([, , , place]) => place),
  "display name place",
);
for (const field of zones.flat()) {
  if (/[|\n`$\\]/.test(field)) {
    throw new Error(`unexpected character in ${field}`);
  }
}

const licenseComment = license
  .trim()
  .split("\n")
  .map((line) => `//${line.trimEnd() ? ` ${line.trimEnd()}` : ""}`)
  .join("\n");

const source = `// Generated by scripts/generate-windows-zones.mjs; don't edit by hand.
//
// Source: Unicode CLDR ${CLDR_TAG}, https://github.com/unicode-org/cldr/tree/${CLDR_TAG}
// - common/supplemental/windowsZones.xml: the territory 001 zone of each Windows time zone, and
//   the Windows display name in the comment above it;
// - common/bcp47/timezone.xml: the current IANA id of each CLDR zone.
//
// The data is licensed under the Unicode License v3:
//
${licenseComment}

// One Windows time zone per line, fields separated by \`|\`: its id without " Standard Time", its
// IANA time zone, the UTC offset in its display name, and the first place its display name lists,
// lower-cased.
export const WINDOWS_ZONES = \`${zones.map((zone) => zone.join("|")).join("\n")}\`;
`;

await writeFile(OUTPUT, source);
console.log(`[ics:windows-zones] ${zones.length} zones from CLDR ${CLDR_TAG}`);
